"""Summarize terminal-decision diagnostics already captured by G008 evaluation.

This module never reruns games or emits replay files. The Kaggle evaluation
runner classifies each loss during its original simulation and embeds the
compact aggregate in ``g008-evaluation.json``.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
from typing import Any

from training.ppo.protocol import write_json


def summarize_report(report: dict[str, Any]) -> dict[str, Any]:
    if report.get("format") != "g008-registered-evaluation/1":
        raise ValueError("failure diagnostics require a registered G008 evaluation report")
    episodes = report.get("episodes")
    if not isinstance(episodes, list) or len(episodes) != 512:
        raise ValueError("failure diagnostics require all 512 registered episode rows")
    losses = [row for row in episodes if isinstance(row, dict) and row.get("result") == "loss"]
    if len(losses) != report.get("summary", {}).get("losses"):
        raise ValueError("loss rows do not reconcile with the evaluation summary")
    if any(not isinstance(row.get("failure_diagnosis"), dict) for row in losses):
        raise ValueError("evaluation report lacks per-loss terminal-decision diagnostics")
    categories = Counter(row["failure_diagnosis"]["category"] for row in losses)
    causes = Counter(cause for row in losses
                     for cause in row["failure_diagnosis"].get("terminal_causes", []))
    by_seat = {
        f"seat-{seat}": dict(sorted(Counter(
            row["failure_diagnosis"]["category"] for row in losses
            if row.get("target_seat") == seat).items()))
        for seat in (0, 1)
    }
    return {
        "format": "g008-failure-diagnostics/2",
        "run_uuid": report.get("run_uuid"),
        "opponent_id": report.get("opponent_id"),
        "candidate_checkpoint_sha256": report.get("candidate_checkpoint_sha256"),
        "games": 512,
        "losses_classified": len(losses),
        "categories": dict(sorted(categories.items())),
        "categories_by_seat": by_seat,
        "terminal_causes": dict(sorted(causes.items())),
        "avoidable_final_decisions": sum(
            bool(row["failure_diagnosis"].get("conditional_avoidable_if_opponent_action_held"))
            for row in losses),
        "interpretation": (
            "Classification uses the terminal decision from each original Kaggle game. "
            "Counterfactuals hold the observed opponent action fixed for one step and "
            "do not prove strategic superiority. No games were rerun and no replay "
            "files were generated by this summarizer."
        ),
    }


def diagnose(report_path: Path, output_path: Path) -> dict[str, Any]:
    report = json.loads(report_path.read_text(encoding="utf-8"))
    summary = summarize_report(report)
    write_json(output_path, summary)
    return summary


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    print(json.dumps(diagnose(args.report, args.output), indent=2))


if __name__ == "__main__":
    main()
